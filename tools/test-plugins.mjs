/*
 * test-plugins.mjs — the plugins a declaration marks `"role": "test"`: instruments and probes a host's
 * own tests create by CLAP id, which no picker lists and no package installs.
 *
 * A test plugin's folder is plugins/<stem>/ like any other: its declaration <stem>.decl.json
 * (schema `$defs.testPlugin`) is the one home of its identity and of the constants its oracle predicts
 * from; its CLAP face, Makefile and oracles are written by hand. From the declaration tools/gen.mjs
 * writes generated/omx_<kernel>_decl.h (the identity and the constants as C macros), and fills the
 * test regions of libomxplugins' table (include/omx_clap_static.h, lib/omx_clap_static.c): the face
 * is linked in, `omx_clap_static_find()` opens it by id, and the table of shipped plugins, the one
 * entry's factory listing, the README, the packages and the release gate never see it.
 */
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { basename, join, resolve } from 'node:path';
import { validate } from './schema-validate.mjs';

const BANNER = '// SPDX-License-Identifier: GPL-3.0-or-later\n// Copyright (C) 2026 Pau Aliagas <linuxnow@gmail.com>\n';

/** The role a raw declaration states: `test`, or `ship` when it states none. */
export const roleOf = (raw) => raw?.role ?? 'ship';

const rawOf = (dir) => {
  const file = join(dir, `${basename(dir)}.decl.json`);
  return existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : undefined;
};

/** Whether plugins/<stem>/ holds a test plugin's declaration. */
export const isTestDir = (dir) => roleOf(rawOf(dir)) === 'test';

/** Every test plugin's folder, sorted. */
export const testPluginDirs = (root) =>
  readdirSync(join(root, 'plugins'))
    .map((n) => join(root, 'plugins', n))
    .filter((p) => isTestDir(p))
    .sort();

/** A test plugin's declaration, validated against the schema's `$defs.testPlugin`; errors name the file. */
export function loadTestDecl(root, dir) {
  const stem = basename(resolve(dir));
  const file = join(dir, `${stem}.decl.json`);
  const d = JSON.parse(readFileSync(file, 'utf8'));
  const schema = JSON.parse(readFileSync(join(root, 'schema', 'plugin.decl.schema.json'), 'utf8'));
  const errs = validate(schema, { $ref: '#/$defs/testPlugin' }, d);
  if (errs.length) throw new Error(`${file}: ${errs.join('; ')}`);
  if (d.stem !== stem) throw new Error(`${file}: stem '${d.stem}' is not the directory's '${stem}'`);
  if (!existsSync(join(dir, 'Makefile'))) throw new Error(`${file}: a test plugin's Makefile is written by hand, and plugins/${stem}/Makefile is missing`);
  return { ...d, dir: resolve(dir) };
}

const macro = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/[^A-Za-z0-9]/g, '_').toUpperCase();

/** generated/omx_<kernel>_decl.h: the identity and the constants, from the declaration alone. */
export function emitTestHeader(d) {
  const K = macro(d.kernel);
  const guard = `OMX_${K}_DECL_H`;
  const constants = Object.entries(d.constants ?? {});
  return `${BANNER}/* GENERATED by tools/gen.mjs from plugins/${d.stem}/${d.stem}.decl.json — DO NOT EDIT BY HAND.
 *
 * ${d.name}: a test plugin (role ${d.role}). Its identity and the constants its face runs with and its
 * oracle predicts from, declared once in the declaration.
 */
#ifndef ${guard}
#define ${guard}

#define OMX_${K}_ROLE "${d.role}"
#define OMX_${K}_NAME "${d.name}"
#define OMX_${K}_VENDOR "${d.vendor}"
#define OMX_${K}_URL "${d.url}"
#define OMX_${K}_VERSION "${d.version}"
#define OMX_${K}_DESCRIPTION "${d.description.replace(/"/g, '\\"')}"
#define OMX_${K}_CLAP_ID "${d.clap.id}"
#define OMX_${K}_CLAP_FEATURES ${d.clap.features.map((f) => `"${f}"`).join(', ')}

/* The declared constants. */
${constants.map(([k, v]) => `#define OMX_${K}_${macro(k)} ${v}`).join('\n')}

#endif /* ${guard} */
`;
}

/** The files gen writes into a test plugin's folder: path relative to it -> text. */
export const generateTest = (d) => ({ [`generated/omx_${d.kernel}_decl.h`]: emitTestHeader(d) });
