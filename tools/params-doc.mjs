/*
 * params-doc.mjs — the parameter reference of every shipped plugin, written from its declaration.
 *
 *   node tools/params-doc.mjs           write docs/plugins/<stem>.md for every plugin and docs/plugins/README.md
 *   node tools/params-doc.mjs --check   write nothing; exit 1 naming each page that is not what the declarations say
 *                                       (make check-params-doc)
 *
 * The text comes from the plugin's descriptor (plugins/<stem>/<stem>.descriptor.json: identity, description, ports, every
 * control with its resolved travel or choices) and the panel its declaration draws (plugins/<stem>/<stem>.decl.json, or
 * the base declaration of a variant: the section keys). It reads no built file, no installed package and no version.
 * A page is the LV2 port group and the CLAP module of a control (tools/descriptor.mjs portGroupsOf): the group path of
 * the control is the page, and its priority counts the groups down in the order their first port comes.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { baseOf } from './variants.mjs';

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = 'docs/plugins';

const BANNER = '<!-- SPDX-License-Identifier: GPL-3.0-or-later -->\n<!-- Copyright (C) 2026 Pau Aliagas <linuxnow@gmail.com> -->\n<!-- Generated by tools/params-doc.mjs from the declarations; edit them and run `make params-doc`. -->\n';

const cell = (s) => String(s).replaceAll('|', '\\|').replaceAll('\n', ' ');
const num = (n) => String(n);

/** The plugin folders that have a descriptor, by stem. */
export function describedStems(root = ROOT) {
  return readdirSync(join(root, 'plugins')).sort().filter((n) => existsSync(join(root, 'plugins', n, `${n}.descriptor.json`)));
}

/** The declaration (raw) whose panel `stem` draws: its own, or its base's for a variant. */
function panelOwner(root, stem) {
  const dir = join(root, 'plugins', stem);
  const own = join(dir, `${stem}.decl.json`);
  if (existsSync(own)) return JSON.parse(readFileSync(own, 'utf8'));
  const base = baseOf(dir);
  if (!base) throw new Error(`plugins/${stem}: no declaration and no base declaration names it`);
  return base.decl;
}

/** The pages of a descriptor: each distinct group path in the order its first control comes, with its LV2 symbol and priority. */
export function pagesOf(descriptor, decl) {
  const sections = new Map((decl.panel?.sections ?? []).map((s) => [s.label, s.key]));
  const pages = [];
  for (const c of descriptor.controls) {
    const path = c.group ?? [];
    const id = path.join('/');
    if (pages.some((p) => p.id === id)) {
      pages.find((p) => p.id === id).controls.push(c);
      continue;
    }
    const last = path[path.length - 1];
    const key = path.length > 1 ? last.toLowerCase().replace(/\s+/g, '') : sections.get(last);
    pages.push({ id, path, key, controls: [c] });
  }
  pages.forEach((p, i) => { p.priority = pages.length - i; });
  return pages;
}

const valueOf = (c) => {
  if (c.kind === 'toggle') return { min: 'off', max: 'on', def: c.default ? 'on' : 'off', step: 'toggle' };
  if (c.kind === 'choice') {
    const at = c.ids.indexOf(c.default);
    return { min: c.values[0], max: c.values[c.values.length - 1], def: `${c.labels[at]} (${c.values[at]})`, step: c.values.map((v, i) => `${v} ${c.labels[i]}`).join(', ') };
  }
  const t = c.travel;
  return { min: num(t.min), max: num(t.max), def: num(t.default), step: t.step === 1 ? 'whole steps' : `continuous, ${t.scale}` };
};

/** The page of one plugin. */
export function pluginPage(root, stem) {
  const descriptor = JSON.parse(readFileSync(join(root, 'plugins', stem, `${stem}.descriptor.json`), 'utf8'));
  const decl = panelOwner(root, stem);
  const pl = descriptor.plugin;
  const pages = pagesOf(descriptor, decl);
  const priorityOf = new Map(pages.map((p) => [p.id, p.priority]));
  const n = descriptor.controls.length;
  const out = [BANNER, `# ${pl.name}`, '', pl.doc, '',
    `- CLAP id: \`${pl.id}\``, `- LV2 URI: \`${pl.uri}\``,
    `- Parameters: ${n}, plus the host's bypass`, '', '## Audio ports', '',
    '| Direction | Name | Role | Channels |', '|---|---|---|---|',
    ...descriptor.ports.map((p) => `| ${p.direction} | ${cell(p.name)} | ${p.role} | ${p.channels} (${p.layout}) |`), '',
    '## Pages', '',
    `A page is where a host shows a parameter. In LV2 each page is a port group, \`pg:group <${pl.uri}#<symbol>>\`, whose \`lv2:displayPriority\` is the number below (a host that shows the higher first, as Zynthian does, shows the pages in port order). In CLAP each page is the module of its parameters (\`clap_param_info.module\`), the page labels joined by \`/\`.`, '',
    '| Page | LV2 group symbol | Priority | CLAP module | Parameters |', '|---|---|---|---|---|',
    ...pages.map((p) => `| ${cell(p.path.join(' / '))} | \`${p.key}\` | ${p.priority} | \`${p.path.join('/')}\` | ${p.controls.length} |`), '',
    '## Parameters', '',
    `Ids are the order below, 0 to ${n - 1}; the bypass takes the next id.`, '',
    '| Id | Symbol | Name | Unit | Min | Max | Default | Step or values | Flags | Page (priority) |', '|---|---|---|---|---|---|---|---|---|---|'];
  for (const c of descriptor.controls) {
    const v = valueOf(c);
    const unit = c.kind === 'travel' ? c.travel.unit : (c.unit ?? '');
    const flags = [c.automatable ? 'automatable' : null, c.group ? null : 'hidden'].filter(Boolean).join(', ');
    const page = c.group ? `${c.group.join(' / ')} (${priorityOf.get(c.group.join('/'))})` : '';
    out.push(`| ${c.id} | \`${c.symbol}\` | ${cell(c.name)} | ${cell(unit)} | ${cell(v.min)} | ${cell(v.max)} | ${cell(v.def)} | ${cell(v.step)} | ${flags} | ${cell(page)} |`);
  }
  out.push('', '## Bypass', '',
    `CLAP: the host's bypass, a parameter named Bypass at id ${n}, flagged automatable, stepped and bypass; 0 is processing, 1 bypassed.`,
    `LV2: the port \`enabled\` (\`lv2:designation lv2:enabled\`), 1 is processing, 0 is bypassed${decl.lv2?.enabledPort === 'first' ? '; it comes before the parameter ports' : '; it comes after the parameter ports'}. The output port \`latency\` reports the latency in frames.`, '');
  return { text: `${out.join('\n')}`, name: pl.name, id: pl.id, uri: pl.uri, doc: pl.doc, controls: n, pages: pages.length };
}

/** Every file docs/plugins holds, by path relative to the repository: the pages and their index. */
export function generate(root = ROOT) {
  const files = {};
  const rows = [];
  for (const stem of describedStems(root)) {
    const p = pluginPage(root, stem);
    files[`${OUT}/${stem}.md`] = p.text;
    rows.push(`| [${p.name}](${stem}.md) | \`${p.id}\` | \`${p.uri}\` | ${p.controls} | ${p.pages} |`);
  }
  files[`${OUT}/README.md`] = [BANNER, '# Plugin parameter reference', '',
    'One page for each plugin: its ids, its audio ports, its pages (the LV2 port groups and CLAP modules a host shows) and a table of every parameter. The pages are generated by `tools/params-doc.mjs` from the plugins\' declarations; `make check-params-doc` fails when a page differs from them.', '',
    '| Plugin | CLAP id | LV2 URI | Parameters | Pages |', '|---|---|---|---|---|', ...rows, ''].join('\n');
  return files;
}

function main(argv) {
  const check = argv.includes('--check');
  const files = generate();
  let stale = 0;
  for (const [rel, text] of Object.entries(files)) {
    const path = join(ROOT, rel);
    const now = existsSync(path) ? readFileSync(path, 'utf8') : null;
    if (now === text) continue;
    if (check) {
      console.error(`params-doc: STALE ${rel} (run \`make params-doc\`)`);
      stale++;
    } else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, text);
      console.log(`params-doc: wrote ${rel}`);
    }
  }
  if (check) {
    // a page no declaration makes any more
    const dir = join(ROOT, OUT);
    for (const f of existsSync(dir) ? readdirSync(dir) : []) {
      if (!files[`${OUT}/${f}`]) { console.error(`params-doc: EXTRA ${OUT}/${f}: no declaration makes it`); stale++; }
    }
  }
  if (stale) process.exit(1);
  if (check) console.log(`params-doc: ${Object.keys(files).length} pages are what the declarations say`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
